//! # fidelogic-cli
//!
//! Fidelogic Vault のローカル運用および暗号鍵ライフサイクル管理を行うネイティブ CLI ツール。
//!
//! ## Overview
//!
//! 本ツールは、ファイルシステム上に永続化された暗号化ストレージ (Vault) の作成、スロット構成の更新
//! (Argon2id パスワード、WebAuthn PRF 鍵、リカバリーコード)、機密エントリの安全な格納・抽出を
//! コマンドラインから実行するための管理者向けインターフェースを提供する。
//!
//! ## ネイティブ環境におけるセキュリティアーキテクチャ
//!
//! - **メモリ保護**: ネイティブ環境の OS 機能を活用し、機密データを保持するバッファに対して
//!   `mlock` (スワップアウト抑止) および `MADV_DONTDUMP` (コアダンプ抑止) を適用する。
//! - **安全なゼロ消去**: プロセス終了時またはエラー発生時には、メモリ上の暗号鍵および復号平文を
//!   揮発性ゼロ書き込みとコンパイラフェンスにより確実に消去する。
//! - **プロファイル連携**: [`fidelogic_core`] とリンクし、完全機能 Vault エンジン (`profile-vault`)
//!   に基づいた暗号処理を実行する。

use fidelogic_core::active_profile;

/// CLI アプリケーションのエントリポイント。
///
/// リンクされているコアエンジンのプロファイル状態を検証し、コマンドラインインターフェースを起動する。
fn main() {
    println!("fidelogic-cli (fidelogic-core: {})", active_profile());
}
